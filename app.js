const $ = (s) => document.querySelector(s);
const escapeHtml = (value) => String(value).replace(/[&<>'"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&#039;', '"': '&quot;' }[c]));
const renderCode = (text) => escapeHtml(text).replace(/`([^`]+)`/g, '<code>$1</code>');
const renderTip = (text) => renderCode(text).replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
const sources = { topics, builtins };
let mode = 'theory';
let modalSource = 'topics';
let modalIndex = 0;

function cardText(topic) {
  const chunks = [topic.title, topic.lead];
  (topic.sections || []).forEach((section) => {
    chunks.push(section.title, ...(section.paragraphs || []), section.syntax || '', section.example || '', section.note || '');
  });
  return chunks.join(' ');
}

function renderRows(items, allItems, source) {
  return items.map((topic) => {
    const index = allItems.indexOf(topic);
    return `<article class="topic-row" id="${source === 'topics' ? 'topic' : 'builtin'}-${index}" data-open-topic="${source}:${index}"><span class="theory-number">${String(index + 1).padStart(2, '0')}</span><div class="topic-row-text"><h3>${escapeHtml(topic.title)}</h3><p>${escapeHtml(topic.lead)}</p></div><button type="button" class="open-topic">Открыть</button></article>`;
  }).join('');
}

function renderNav(items, visible, source) {
  const prefix = source === 'topics' ? 'topic' : 'builtin';
  return items.map((topic, i) => `<a href="#${prefix}-${i}" data-open-topic="${source}:${i}" class="${visible.includes(topic) ? '' : 'hidden'}">${i + 1}. ${escapeHtml(topic.title)}</a>`).join('');
}

function renderSection(section, index) {
  const paragraphs = (section.paragraphs || []).map((text) => `<p>${renderCode(text)}</p>`).join('');
  const syntax = section.syntax ? `<div><span class="block-label">КОНСТРУКЦИЯ</span><pre>${escapeHtml(section.syntax)}</pre></div>` : '';
  const example = section.example ? `<div><span class="block-label">ПРИМЕР</span><pre>${escapeHtml(section.example)}</pre></div>` : '';
  const grid = syntax || example ? `<div class="code-grid">${syntax}${example}</div>` : '';
  const note = section.note ? `<p class="tip"><strong>Не перепутать:</strong> ${renderTip(section.note)}</p>` : '';
  return `<section class="subtopic" id="sub-${index}"><h3>${escapeHtml(section.title)}</h3><div class="prose">${paragraphs}</div>${grid}${note}</section>`;
}

function openModal(source, index) {
  const list = sources[source];
  const topic = list?.[index];
  if (!topic) return;
  modalSource = source;
  modalIndex = index;
  $('#modal-kicker').textContent = source === 'builtins' ? 'Встроенные функции' : 'Основная теория';
  $('#modal-title').textContent = topic.title;
  $('#modal-toc').innerHTML = topic.sections.map((section, i) => `<a href="#sub-${i}">${escapeHtml(section.title)}</a>`).join('');
  $('#modal-body').innerHTML = topic.sections.map(renderSection).join('');
  $('#modal-body').scrollTop = 0;
  $('#modal-prev').disabled = index <= 0;
  $('#modal-next').disabled = index >= list.length - 1;
  $('#topic-modal').hidden = false;
  document.body.classList.add('modal-open');
  const prefix = source === 'topics' ? 'topic' : 'builtin';
  history.replaceState(null, '', `#${prefix}-${index}`);
  $('#modal-close').focus();
}

function closeModal() {
  if ($('#topic-modal').hidden) return;
  $('#topic-modal').hidden = true;
  document.body.classList.remove('modal-open');
  history.replaceState(null, '', '#top');
}

function render() {
  const query = $('#search-input').value.trim().toLowerCase();
  const matches = (value) => !query || value.toLowerCase().includes(query);
  const activeFilter = document.querySelector('.filter.active')?.dataset.filter || 'Все';
  const visibleTopics = topics.filter((topic) => matches(cardText(topic)));
  const visibleBuiltins = builtins.filter((topic) => matches(cardText(topic)));
  const visibleGroups = Object.entries(methods).filter(([name, rows]) => (activeFilter === 'Все' || name === activeFilter) && matches(`${name} ${rows.flat().join(' ')}`));

  if (mode === 'theory') $('#topic-nav').innerHTML = renderNav(topics, visibleTopics, 'topics');
  else if (mode === 'builtins') $('#topic-nav').innerHTML = renderNav(builtins, visibleBuiltins, 'builtins');
  else $('#topic-nav').innerHTML = Object.keys(methods).map((name) => `<a href="#methods-list">${escapeHtml(name)}</a>`).join('');

  $('#theory-list').innerHTML = renderRows(visibleTopics, topics, 'topics');
  $('#builtins-list').innerHTML = renderRows(visibleBuiltins, builtins, 'builtins');
  $('#methods-list').innerHTML = visibleGroups.map(([group, rows]) => {
    const receiver = group.startsWith('str') ? 's' : group.startsWith('list') ? 'a' : group.startsWith('tuple') ? 't' : group.startsWith('dict') ? 'd' : group.startsWith('frozenset') ? 'fs' : group.startsWith('set') ? 's' : '';
    return `<article class="method-group"><h3>${escapeHtml(group)}</h3>${rows.map(([method, text, example]) => `<div class="method-row"><code>${escapeHtml(method)}</code><span>${escapeHtml(text)}</span><div class="method-example">${escapeHtml(example || `${receiver}${method}`)}</div></div>`).join('')}</article>`;
  }).join('');

  const visibleCount = mode === 'theory' ? visibleTopics.length : mode === 'builtins' ? visibleBuiltins.length : visibleGroups.length;
  $('#empty-state').hidden = visibleCount > 0;
}

function setMode(nextMode) {
  mode = nextMode;
  document.querySelectorAll('.switch-button').forEach((button) => {
    const active = button.dataset.mode === mode;
    button.classList.toggle('active', active);
    button.setAttribute('aria-selected', String(active));
  });
  $('#quick-section').hidden = mode !== 'theory';
  $('#theory-section').hidden = mode !== 'theory';
  $('#builtins-section').hidden = mode !== 'builtins';
  $('#methods-section').hidden = mode !== 'methods';
  render();
}

function parseOpenTarget(value) {
  const [source, index] = String(value || '').split(':');
  if (!sources[source] || Number.isNaN(Number(index))) return null;
  return [source, Number(index)];
}

function init() {
  $('#quick-grid').innerHTML = quick.map(([label, code]) => `<article class="quick-card"><p>${escapeHtml(label)}</p><code>${escapeHtml(code)}</code></article>`).join('');
  $('#method-filters').innerHTML = ['Все', ...Object.keys(methods)].map((name, i) => `<button class="filter ${i === 0 ? 'active' : ''}" data-filter="${escapeHtml(name)}">${escapeHtml(name)}</button>`).join('');
  $('#topic-count').textContent = topics.length;
  $('#builtin-count').textContent = builtins.length;
  $('#method-count').textContent = Object.values(methods).flat().length;
  $('#search-input').addEventListener('input', render);
  $('.content-switch').addEventListener('click', (e) => {
    if (e.target.matches('.switch-button')) setMode(e.target.dataset.mode);
  });
  $('#method-filters').addEventListener('click', (e) => {
    if (!e.target.matches('.filter')) return;
    document.querySelectorAll('.filter').forEach((button) => button.classList.remove('active'));
    e.target.classList.add('active');
    render();
  });
  document.addEventListener('click', (e) => {
    const openFrom = e.target.closest('[data-open-topic]');
    if (openFrom) {
      e.preventDefault();
      const target = parseOpenTarget(openFrom.dataset.openTopic);
      if (target) openModal(target[0], target[1]);
      return;
    }
    if (e.target.closest('[data-close-modal]')) closeModal();
  });
  $('#modal-toc').addEventListener('click', (e) => {
    const link = e.target.closest('a[href^="#sub-"]');
    if (!link) return;
    e.preventDefault();
    $('#modal-body').querySelector(link.getAttribute('href'))?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  });
  $('#modal-prev').addEventListener('click', () => openModal(modalSource, modalIndex - 1));
  $('#modal-next').addEventListener('click', () => openModal(modalSource, modalIndex + 1));
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      if (!$('#topic-modal').hidden) {
        closeModal();
        return;
      }
      $('#search-input').value = '';
      $('#search-input').blur();
      render();
    }
  });
  document.querySelectorAll('[data-query]').forEach((button) => button.addEventListener('click', () => {
    $('#search-input').value = button.dataset.query;
    render();
    $('#search-input').focus();
  }));
  const top = $('#to-top');
  window.addEventListener('scroll', () => top.classList.toggle('visible', window.scrollY > 500));
  top.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
  setMode('theory');
  const hash = location.hash.slice(1);
  if (hash.startsWith('topic-')) openModal('topics', Number(hash.slice(6)));
  if (hash.startsWith('builtin-')) {
    setMode('builtins');
    openModal('builtins', Number(hash.slice(8)));
  }
}

init();
